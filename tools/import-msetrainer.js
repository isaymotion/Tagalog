#!/usr/bin/env node
/* Copies the Tagalog lines of the MSE Trainer app (isaymotion/MSEtrainer) into tools/extra-texts/msetrainer.txt,
   so this repo's audio job records them. The MSE Trainer plays the clips from isaymotion.github.io/tagalog/audio/.
     node tools/import-msetrainer.js /path/to/MSEtrainer
   Rule shared with the MSE Trainer (speakable() in its js/app.js): stage directions in parentheses are skipped. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const src = path.resolve(process.argv[2] || '../MSEtrainer');
const ctx = { console }; vm.createContext(ctx);
['js/data.js', 'js/data-tl.js'].forEach((f) => vm.runInContext(fs.readFileSync(path.join(src, f), 'utf8'), ctx, { filename: f }));
const V = vm.runInContext('V', ctx);
const speakable = (t) => String(t).replace(/\([^)]*\)/g, ' ').replace(/\s+/g, ' ').trim();
const out = new Set();
const add = (t) => { const tl = speakable(t.split(' || ')[0]); if (tl && /[a-zA-ZñÑ]/.test(tl)) out.add(tl); };
V.filter((v) => v.lang === 'tl').forEach((v) => {
  v.x.split('\n').forEach((l) => { if (/^[CP]:/.test(l) && l.includes(' || ')) add(l.slice(2).trim()); });
  if (v.ask) add(v.ask);
});
const file = path.join(__dirname, 'extra-texts', 'msetrainer.txt');
fs.writeFileSync(file, '# Tagalog lines from the MSE Trainer app. Generated by tools/import-msetrainer.js; do not edit by hand.\n' + [...out].join('\n') + '\n');
console.log('Wrote', out.size, 'lines to', path.relative(process.cwd(), file));
